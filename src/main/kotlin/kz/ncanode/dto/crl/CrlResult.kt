package kz.ncanode.dto.crl

enum class CrlResult {
    REVOKED,

    /** Серийник не найден ни в одном пригодном CRL издателя. */
    ACTIVE,

    /**
     * Список издателя найден и криптографически проверен, серийника в нём нет,
     * но период действия списка на момент проверки истёк (`nextUpdate` в
     * прошлом либо отсутствует).
     *
     * Отдельный исход, а не ACTIVE: п. 18 Правил формирования и проверки
     * подлинности ЭЦП (приказ МИИ РК №500/НҚ) прямо называет истечение периода
     * действия CRL отрицательным результатом его проверки. Отсутствие
     * серийника в протухшем списке ничего не говорит об отзывах, случившихся
     * после `nextUpdate`.
     */
    EXPIRED,

    /**
     * Проверить было нечем: CRL выключен конфигом, ни один CRL издателя
     * не найден в кэше, либо все найденные отброшены (битая подпись,
     * необработанное critical-расширение). Это «проверки не было», а не
     * «чисто»: нефатален в AND-режиме (легаси-CA без опубликованного CRL —
     * легитимный случай), но не может быть fallback-источником при
     * недоступном OCSP (см. `CertificateWrapper.isValid`).
     */
    UNAVAILABLE,
}
