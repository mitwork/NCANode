package kz.ncanode.dto.crl

enum class CrlResult {
    REVOKED,

    /** Серийник не найден ни в одном пригодном CRL издателя. */
    ACTIVE,

    /**
     * Проверить было нечем: CRL выключен конфигом, ни один CRL издателя
     * не найден в кэше, либо все найденные отброшены (битая подпись,
     * необработанное critical-расширение). Это «проверки не было», а не
     * «чисто»: нефатален в AND-режиме (легаси-CA без опубликованного CRL —
     * легитимный случай), но не может быть fallback-источником при
     * недоступном OCSP (см. `CertificateWrapper.isValid`).
     */
    UNAVAILABLE,
}
