package kz.ncanode.dto.ades

/**
 * Итог проверки подписи в терминах ETSI EN 319 102-1.
 *
 * Отвечает на вопрос, которого не хватает флагу `valid`: если подпись не
 * принята, то потому что она **плохая** или потому что её **не удалось
 * проверить**. Разница практическая: в первом случае документу верить нельзя,
 * во втором — не хватило данных (нет цепочки, недоступен отзыв, не сошлась
 * метка), и вопрос решается доступом к инфраструктуре, а не переподписанием.
 *
 * Тот же словарь показывает валидатор НУЦ, так что вердикты двух инструментов
 * можно сравнивать напрямую.
 */
enum class AdesValidationStatus {
    /** Проверено полностью, замечаний нет. */
    VALID,

    /** Подпись недействительна: криптография, привязка или отзыв до подписи. */
    INVALID,

    /** Проверить до конца не удалось — см. [AdesSubIndication]. */
    INDETERMINATE,
}
