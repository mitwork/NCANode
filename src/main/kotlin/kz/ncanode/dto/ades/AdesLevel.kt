package kz.ncanode.dto.ades

/**
 * Уровень AdES-подписи (ETSI EN 319 122 для CAdES, 319 132 для XAdES,
 * 319 142 для PAdES).
 *
 * Уровни **нарастающие**, а не альтернативные: каждый следующий добавляется
 * поверх предыдущего, поэтому подпись уровня LTA содержит в себе и B, и T,
 * и LT. Отсюда [isAtLeast] и порядок применения при подписи.
 *
 *  - **B** — базовый: подписанные атрибуты, привязывающие подпись к
 *    сертификату подписанта (`signingCertificateV2`) и к использованным
 *    алгоритмам (`cmsAlgorithmProtection`).
 *  - **T** — плюс метка доверенного времени на значение подписи: доказывает,
 *    что подпись существовала не позже genTime метки.
 *  - **LT** — плюс встроенные данные для проверки (цепочка сертификатов и
 *    сведения об отзыве на момент подписи): подпись проверяема без обращения
 *    к сети и после истечения сертификата.
 *  - **LTA** — плюс архивная метка времени поверх всего перечисленного:
 *    защищает от устаревания алгоритмов, требует периодического обновления.
 */
enum class AdesLevel(private val rank: Int) {
    B(0),
    T(1),
    LT(2),
    LTA(3),
    ;

    /** `true`, если этот уровень включает в себя [other]. */
    fun isAtLeast(other: AdesLevel): Boolean = rank >= other.rank
}
