package kz.ncanode.dto.ades

/**
 * Причина, по которой подпись не получила статус
 * [AdesValidationStatus.VALID] (ETSI EN 319 102-1).
 *
 * Выдаётся только то, что мы действительно установили: если причину доказать
 * нечем, поле остаётся пустым, а не заполняется правдоподобной догадкой.
 */
enum class AdesSubIndication {
    /** В подписи нет сертификата подписанта — проверять нечем. */
    NO_SIGNING_CERTIFICATE_FOUND,

    /** Значение подписи не сходится: содержимое или подпись изменены. */
    SIG_CRYPTO_FAILURE,

    /** Подпись привязана к другому сертификату, чем приложенный. */
    CERT_HASH_MISMATCH,

    /** Метка времени не прошла проверку — доказанного момента подписи нет. */
    TIMESTAMP_INVALID,

    /** Сертификат не действовал в момент подписи, и доказать обратное нечем. */
    OUT_OF_BOUNDS_NO_POE,

    /** Сертификат отозван до момента подписи. */
    CERT_REVOKED,

    /** Сертификат отозван, а доказательства, что подпись раньше отзыва, нет. */
    REVOKED_NO_POE,

    /** Данных об отзыве на момент подписи получить не удалось. */
    REVOCATION_DATA_MISSING,
}
