package kz.ncanode.dto.certificate

/**
 * Итог проверки отзыва по одному каналу (OCSP-responder или CRL) —
 * публикуется в `revocations[].result` ответа верификации.
 *
 * Флаг `revoked` в том же элементе остаётся для обратной совместимости,
 * но он бинарный и не отличает «проверено, чисто» от «проверить не удалось».
 * Клиент, которому нужна строгая политика «оба канала обязаны ответить»
 * (историческое AND-поведение до появления OCSP→CRL fallback), может
 * реализовать её сам: `valid && revocations.none { it.result == UNAVAILABLE }`.
 */
enum class RevocationResult {
    /** Канал ответил: сертификат не отозван. */
    ACTIVE,

    /** Канал ответил: сертификат отозван (см. `revocationTime` + `reason`). */
    REVOKED,

    /**
     * Ответ получен, но доверия ему нет (OCSP: битый nonce/подпись,
     * авторитетный unknown). Фатален для верификации.
     */
    UNKNOWN,

    /**
     * Канал недоступен: OCSP-responder не отвечает либо пригодного CRL
     * издателя нет в кэше. Вердикт мог быть вынесен деградированно —
     * по данным другого канала.
     */
    UNAVAILABLE,
}
