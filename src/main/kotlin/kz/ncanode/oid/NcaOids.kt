package kz.ncanode.oid

/**
 * Официальный OID-реестр УЦ Республики Казахстан, релевантных для NCALayer:
 *  - `1.2.398.3.1.x` — Корневой Удостоверяющий Центр РК (КУЦ РК).
 *  - `1.2.398.3.3.x` — Национальный Удостоверяющий Центр РК (НУЦ РК) — выпускает
 *                     cert'ы для физлиц и юрлиц, основной для NCALayer-экосистемы.
 *
 * Источник: официальный реестр OID НУЦ РК (pki.gov.kz).
 *
 * NCA-сертификат несёт набор EKU из нескольких независимых осей:
 *  - **Тип пользователя** (`.3.3.4.1.x`) — физлицо vs юр.лицо и роль внутри.
 *  - **Полномочия в системе НУЦ РК** (`.3.3.4.2.x`) — для внутренних cert'ов НУЦ.
 *  - **Метод идентификации** (`.3.3.4.3.x`) — как идентифицировали (ЦОН, удалённо, AI Platform).
 *  - **Хранилище ключа** (`.3.3.5.x`) — где приватный ключ живёт.
 *
 * Реальный cert обычно несёт по одному OID из каждой релевантной оси: например
 * физлицо, идентифицированное удалённо через DigitalID, с ключом в PKCS12-файле:
 * `EKU_INDIVIDUAL` + `EKU_IDENT_REMOTE` + `EKU_STORAGE_PKCS12`.
 */
object NcaOids {

    // =====================================================================
    // 1.2.398.3.1.x  — Корневой УЦ РК (КУЦ РК)
    // =====================================================================

    /** Регламент КУЦ РК. Документационный OID, в extension'ах cert'ов не используется. */
    const val REGULATION_ROOT_CA = "1.2.398.3.1.1.1"

    /**
     * Политики применения регистрационных свидетельств КУЦ РК.
     *
     * Используется в `certificatePolicies` extension'е Root cert'а НУЦ РК
     * с CPS URI `http://root.gov.kz/cps`.
     *
     * Примечание: PHP-проект pki.mitwork клал этот OID в `extendedKeyUsage`,
     * но реальный Root cert НУЦ кладёт его в `certificatePolicies` (что
     * семантически правильно — это policy OID).
     */
    const val POLICY_ROOT_CA = "1.2.398.3.1.2"

    // =====================================================================
    // 1.2.398.3.3.1.x  — Регламент НУЦ РК
    // =====================================================================

    /**
     * Регламент НУЦ РК.
     *
     * Формально это OID документа-регламента, не EKU. PHP-проект pki.mitwork
     * клал его в extendedKeyUsage CA-cert'а, но **реальный NCA Intermediate
     * не имеет extendedKeyUsage extension вообще** — этот OID просто
     * документационный, в cert'ах не используется как extension-значение.
     */
    const val REGULATION_NCA = "1.2.398.3.3.1.1"

    /**
     * Wrapper-OID политик НУЦ РК.
     * Используется в `certificatePolicies` extension реальных Intermediate
     * CA-cert'ов вместо конкретной политики из `.3.3.2.1..4`.
     */
    const val POLICY_NCA_WRAPPER = "1.2.398.3.3.2"

    // =====================================================================
    // 1.2.398.3.3.2.x  — Политики применения регистрационных свидетельств НУЦ РК
    // =====================================================================

    /** ЭЦП (sign) юридических лиц. */
    const val POLICY_LEGAL_SIGN = "1.2.398.3.3.2.1"

    /** Аутентификация юридических лиц. */
    const val POLICY_LEGAL_AUTH = "1.2.398.3.3.2.2"

    /** ЭЦП (sign) физических лиц. */
    const val POLICY_PERSON_SIGN = "1.2.398.3.3.2.3"

    /** Аутентификация физических лиц. */
    const val POLICY_PERSON_AUTH = "1.2.398.3.3.2.4"

    /** Технологические SSL регистрационные свидетельства НУЦ. */
    const val POLICY_SSL_TECH = "1.2.398.3.3.2.5"

    // ---- TSA policies (1.2.398.3.3.2.6.x) ----

    /**
     * TSA на алгоритме ГОСТ 34.310-2004 с NCA-OID
     * (`1.2.398.3.10.1.1.1.2`).
     */
    const val POLICY_TSA_GOST_2004_NATIVE = "1.2.398.3.3.2.6.1"

    /** TSA на алгоритме RSA-SHA256. */
    const val POLICY_TSA_RSA_SHA256 = "1.2.398.3.3.2.6.2"

    /**
     * TSA на алгоритме ГОСТ 34.310-2004 с российским OID
     * (`1.3.6.1.4.1.6801.1.2.2`).
     */
    const val POLICY_TSA_GOST_2004_RUSSIAN_OID = "1.2.398.3.3.2.6.3"

    /**
     * TSA на алгоритме СТ РК ГОСТ Р 34.10-2015 (`1.2.398.3.10.1.1.2.3`).
     * Современный, используется по умолчанию для GOST 2015-ключей.
     */
    const val POLICY_TSA_GOST_2015 = "1.2.398.3.3.2.6.4"

    // =====================================================================
    // 1.2.398.3.3.4.1.x  — User type (тип пользователя)
    // =====================================================================

    /** Физическое лицо. */
    const val EKU_INDIVIDUAL = "1.2.398.3.3.4.1.1"

    /** Юридическое лицо / совместное предпринимательство. */
    const val EKU_LEGAL = "1.2.398.3.3.4.1.2"

    /** Первый руководитель юр.лица (CEO). */
    const val EKU_LEGAL_CEO = "1.2.398.3.3.4.1.2.1"

    /** Лицо, наделённое правом подписи. */
    const val EKU_LEGAL_CAN_SIGN = "1.2.398.3.3.4.1.2.2"

    /** Лицо с правом подписи финансовых документов (фин.директор, главбух). */
    const val EKU_LEGAL_CAN_SIGN_FINANCIAL = "1.2.398.3.3.4.1.2.3"

    /** Сотрудник отдела кадров. */
    const val EKU_LEGAL_HR = "1.2.398.3.3.4.1.2.4"

    /** Сотрудник организации (общий тип). */
    const val EKU_LEGAL_EMPLOYEE = "1.2.398.3.3.4.1.2.5"

    // =====================================================================
    // 1.2.398.3.3.4.2.x  — NCA privileges (полномочия в ИС НУЦ РК)
    // =====================================================================

    /** Wrapper-OID для полномочий в инфраструктуре НУЦ РК. */
    const val EKU_NCA_PRIVILEGES = "1.2.398.3.3.4.2"

    /** Администратор НУЦ РК. */
    const val EKU_NCA_ADMIN = "1.2.398.3.3.4.2.1"

    /** Менеджер НУЦ РК. */
    const val EKU_NCA_MANAGER = "1.2.398.3.3.4.2.2"

    /** Оператор НУЦ РК. */
    const val EKU_NCA_OPERATOR = "1.2.398.3.3.4.2.3"

    // =====================================================================
    // 1.2.398.3.3.4.3.x  — Identification method (метод идентификации)
    // =====================================================================

    /**
     * Wrapper-OID. В реальных cert'ах обычно встречается сам по себе,
     * без явного sub-OID'а — означает "пользователь идентифицирован,
     * способ не уточнён" (legacy форма).
     */
    const val EKU_IDENTIFICATION = "1.2.398.3.3.4.3"

    /** Идентификация через оператора ЦОН (контактная, очная). */
    const val EKU_IDENT_BY_OPERATOR = "1.2.398.3.3.4.3.1"

    /** Удалённая идентификация (общий wrapper). */
    const val EKU_IDENT_REMOTE = "1.2.398.3.3.4.3.2"

    /** Удалённая идентификация через Digital-ID. */
    const val EKU_IDENT_REMOTE_DIGITAL_ID = "1.2.398.3.3.4.3.2.1"

    /** Удалённая идентификация через AI Platform (новый метод). */
    const val EKU_IDENT_REMOTE_AI_PLATFORM = "1.2.398.3.3.4.3.2.2"

    // =====================================================================
    // 1.2.398.3.3.5.x  — Key storage (где живёт приватный ключ)
    // =====================================================================

    /** Wrapper: файловое хранилище. */
    const val EKU_STORAGE_FILE = "1.2.398.3.3.5.1"

    /** Файловое хранилище: PKCS12 (P12-файл). */
    const val EKU_STORAGE_PKCS12 = "1.2.398.3.3.5.1.1"

    /** Файловое хранилище: JKS (Java KeyStore). */
    const val EKU_STORAGE_JKS = "1.2.398.3.3.5.1.2"

    /** Wrapper: защищённый носитель. */
    const val EKU_STORAGE_SECURE_CARRIER = "1.2.398.3.3.5.2"

    /** Удостоверение личности (eID). */
    const val EKU_STORAGE_EID = "1.2.398.3.3.5.2.1"

    /** Kaztoken. */
    const val EKU_STORAGE_KAZTOKEN = "1.2.398.3.3.5.2.2"

    /** eToken Java. */
    const val EKU_STORAGE_ETOKEN_JAVA = "1.2.398.3.3.5.2.3"

    /** eToken 5110. */
    const val EKU_STORAGE_ETOKEN_5110 = "1.2.398.3.3.5.2.4"

    /** JaCarta. */
    const val EKU_STORAGE_JACARTA = "1.2.398.3.3.5.2.5"

    /** aKey. */
    const val EKU_STORAGE_AKEY = "1.2.398.3.3.5.2.6"

    /** SIM-карта. */
    const val EKU_STORAGE_SIM = "1.2.398.3.3.5.2.7"

    /** Wrapper: облачное хранилище. */
    const val EKU_STORAGE_CLOUD = "1.2.398.3.3.5.3"

    /** Облачное хранилище: Certex Cloud. */
    const val EKU_STORAGE_CERTEX_CLOUD = "1.2.398.3.3.5.3.1"
}
