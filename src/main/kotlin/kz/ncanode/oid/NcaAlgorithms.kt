package kz.ncanode.oid

/**
 * Криптографические алгоритмы НУЦ РК.
 *
 * Все OID лежат в namespace `1.2.398.3.10.x` — отдельная иерархия от
 * "пользовательских" EKU-OID'ов в [NcaOids]. Эти OID-ы используются как:
 *
 *  - `AlgorithmIdentifier` в `SubjectPublicKeyInfo` сертификата.
 *  - `signatureAlgorithm` в подписанных структурах (CMS, CRL, OCSP).
 *  - `digestAlgorithm` в TSP-импринтах.
 *
 * Все ГОСТ-алгоритмы НУЦ РК — Kazakhstan-specific aliases поверх соответствующих
 * российских ГОСТ-стандартов (ГОСТ 34.310-2004 ≈ ГОСТ Р 34.10-2001;
 * СТ РК ГОСТ Р 34.10-2015 ≈ ГОСТ Р 34.10-2012).
 */
object NcaAlgorithms {

    // =====================================================================
    // 1.2.398.3.10.1.1.x — Signature algorithms
    // =====================================================================

    // ---- ГОСТ 34.310-2004 (legacy, эпоха «GOST 95») ----

    /** Подпись ГОСТ 34.310-2004 на хэш-параметрах `.1.0` (тестовых). */
    const val SIG_GOST_2004_HASH_TEST = "1.2.398.3.10.1.1.1.2.1"

    /** Подпись ГОСТ 34.310-2004 на хэш-параметрах `.1.1` (боевых). */
    const val SIG_GOST_2004_HASH_PROD = "1.2.398.3.10.1.1.1.2.2"

    // ---- СТ РК ГОСТ Р 34.10-2015 (modern, эпоха «GOST 2015») ----

    /** Ключ СТ РК ГОСТ Р 34.10-2015, 256-битный. */
    const val KEY_GOST_2015_256 = "1.2.398.3.10.1.1.2.1"

    /** Ключ СТ РК ГОСТ Р 34.10-2015, 512-битный. */
    const val KEY_GOST_2015_512 = "1.2.398.3.10.1.1.2.2"

    /** Подпись СТ РК ГОСТ Р 34.10-2015 с хэшем СТ РК ГОСТ Р 34.11-2015 (256). */
    const val SIG_GOST_2015_256 = "1.2.398.3.10.1.1.2.3.1"

    /** Подпись СТ РК ГОСТ Р 34.10-2015 с хэшем СТ РК ГОСТ Р 34.11-2015 (512). */
    const val SIG_GOST_2015_512 = "1.2.398.3.10.1.1.2.3.2"

    // =====================================================================
    // 1.2.398.3.10.1.3.x — Hash algorithms
    // =====================================================================

    /** ГОСТ 34.11-95 (legacy hash, 256 bit output). */
    const val HASH_GOST_95 = "1.2.398.3.10.1.3.1"

    /** ГОСТ Р 34.11-2015 / Streebog (256-битный output). */
    const val HASH_GOST_2015_256 = "1.2.398.3.10.1.3.2"

    /** ГОСТ Р 34.11-2015 / Streebog (512-битный output). */
    const val HASH_GOST_2015_512 = "1.2.398.3.10.1.3.3"

    // =====================================================================
    // 1.2.398.3.10.1.2.x — Encryption (для справки, для целей verify не используем)
    // =====================================================================

    /** ГОСТ 28147-89 — симметричное шифрование. */
    const val ENC_GOST_28147 = "1.2.398.3.10.1.2.1"

    // =====================================================================
    // 1.2.398.3.10.1.4.x — Key agreement (для справки)
    // =====================================================================

    /** Согласование ключа на ГОСТ Р 34.10-2015 (256-bit). */
    const val KEX_GOST_2015_256 = "1.2.398.3.10.1.4.1.1"

    /** Согласование ключа на ГОСТ Р 34.10-2015 (512-bit). */
    const val KEX_GOST_2015_512 = "1.2.398.3.10.1.4.1.2"
}
